-- V2__create_url_mappings_table.sql
-- Drop the old 'links' table from V1 and create the proper schema

DROP TABLE IF EXISTS links;

CREATE TABLE url_mappings (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    short_code  VARCHAR(12)   NOT NULL UNIQUE,
    original_url TEXT         NOT NULL,
    created_at  TIMESTAMPTZ   NOT NULL DEFAULT CURRENT_TIMESTAMP,
    expires_at  TIMESTAMPTZ,
    active      BOOLEAN       NOT NULL DEFAULT TRUE
);

-- Index for fast lookup by short_code (this is the most common query)
CREATE INDEX idx_url_mappings_short_code ON url_mappings (short_code);
